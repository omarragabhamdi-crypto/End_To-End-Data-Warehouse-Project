----------------------------------------------------------
-- VALIDATION: FACT SALES
----------------------------------------------------------
----------------------------------------------------------
-- Total fact rows
----------------------------------------------------------
SELECT COUNT(*) AS total_sales
FROM gold.fact_sales;
----------------------------------------------------------
-- NULL customer keys
----------------------------------------------------------
SELECT *
FROM gold.fact_sales
WHERE customer_key IS NULL;
----------------------------------------------------------
-- NULL product keys
----------------------------------------------------------
SELECT *
FROM gold.fact_sales
WHERE product_key IS NULL;
----------------------------------------------------------
-- Negative sales check
----------------------------------------------------------
SELECT *
FROM gold.fact_sales
WHERE sales_amount < 0;
